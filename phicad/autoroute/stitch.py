#!/usr/bin/env python3
"""Drop the power and ground balls of a BGA onto their planes.

An autorouter fans out what it can reach and gives up quietly on the rest.  On a
fine-pitch BGA that leaves inner power and ground balls with a stub and no way
down: the net is a plane on an inner layer, and nothing but a via gets there.
The ratsnest shows them as unconnected pads on a net that is, everywhere else,
obviously connected -- so it reads as a routing remainder rather than the
missing fanout it is.

This places the dogbone the router did not: a via in the diagonal gap between
four balls, and a short trace from the pad to it.

    ball pitch 0.80 mm, pad 0.40 mm, via 0.45 mm
    diagonal gap centre sits 0.566 mm from each of the four ball centres
    clearance = 0.566 - 0.200 (pad radius) - 0.225 (via radius) = 0.141 mm

which clears a 0.1 mm rule.  Each candidate site is checked against the vias and
pads already there, and a ball is left alone if every diagonal is taken -- this
never forces one in.

Which pads to stitch comes from KiCad's DRC report, not from guessing: only pads
DRC actually reports as unconnected are touched.

    python3 stitch.py board.kicad_pcb --plane GND=In1.Cu --plane 3V3=In2.Cu
    python3 stitch.py board.kicad_pcb --plane GND=In1.Cu --plane 3V3=In2.Cu --apply
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cli_path import find_cli  # noqa: E402


def run_drc(cli: str, board: Path) -> dict:
    report = Path(tempfile.mkstemp(suffix=".drc.json")[1])
    try:
        proc = subprocess.run(
            [cli, "pcb", "drc", "--format", "json", "--severity-all",
             "--refill-zones", "-o", str(report), str(board)],
            capture_output=True, text=True,
            env=dict(os.environ, KICAD_RUN_FROM_BUILD_DIR="1"))
        if proc.returncode != 0:
            raise SystemExit(f"drc failed: {proc.stdout}{proc.stderr}")
        return json.loads(report.read_text())
    finally:
        report.unlink(missing_ok=True)


def sexp_end(text: str, start: int) -> int:
    depth = 0
    for i in range(text.index("(", start), len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("unbalanced s-expression")


def footprints(text: str):
    """(ref, ox, oy, rot, [(pad, x, y, net)]) with pad positions made absolute."""
    for m in re.finditer(r"\(footprint ", text):
        end = sexp_end(text, m.start())
        blk = text[m.start():end]
        ref = re.search(r'\(property "Reference" "([^"]+)"', blk)
        if not ref:
            continue
        # Two spellings of the same thing.  A board written by this fork places a
        # footprint with (transform (translate X Y) (rotate A)); one written by
        # pcbnew, or generated by hand, uses (at X Y A).  A board that has been
        # through kicad-cli comes back in the first form even if it went in as the
        # second, so anything reading a routed board has to accept both.
        tr = re.search(r"\(transform\s*\(translate ([-\d.]+) ([-\d.]+)\)\s*"
                       r"\(rotate ([-\d.]+)\)", blk)
        if tr:
            ox, oy, deg = float(tr.group(1)), float(tr.group(2)), float(tr.group(3))
        else:
            at = re.search(r"\n\t\t\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)", blk)
            if not at:
                continue
            ox, oy, deg = float(at.group(1)), float(at.group(2)), float(at.group(3) or 0)
        rot = math.radians(deg)
        pads = []
        for pm in re.finditer(r'\(pad "([^"]+)"', blk):
            # The pad's OWN s-expression, not a fixed-size window.  A pad with no
            # (net ...) -- a no-connect ball, and on this part there are more of
            # those than there are netted ones -- otherwise inherits the net of
            # whichever pad follows it in the file, which reads as a perfectly
            # ordinary GND ball and gets a via dropped on it.
            seg = blk[pm.start():sexp_end(blk, pm.start())]
            pat = re.search(r"\(at ([-\d.]+) ([-\d.]+)", seg)
            net = re.search(r'\(net "([^"]+)"', seg)
            if not (pat and net):
                continue
            px, py = float(pat.group(1)), float(pat.group(2))
            # A pad's (at ...) is local and unrotated; the footprint's rotation is
            # applied on top of it.  KiCad's y axis points down, so a positive
            # rotation turns clockwise on screen and the sign here follows that.
            rx = ox + px * math.cos(rot) - py * math.sin(rot)
            ry = oy + px * math.sin(rot) + py * math.cos(rot)
            pads.append((pm.group(1), rx, ry, net.group(1)))
        yield ref.group(1), ox, oy, rot, pads


def existing(text: str):
    vias, pads = [], []
    for m in re.finditer(r"\(via\b", text):
        blk = text[m.start():sexp_end(text, m.start())]
        at = re.search(r"\(at ([-\d.]+) ([-\d.]+)\)", blk)
        if at:
            vias.append((float(at.group(1)), float(at.group(2))))
    for _ref, _ox, _oy, _rot, ps in footprints(text):
        pads.extend((x, y) for _n, x, y, _net in ps)
    return vias, pads


def unconnected_pads(drc: dict, nets: set[str]) -> set[tuple[str, str]]:
    """{(refdes, pad)} that DRC calls unconnected on one of `nets`."""
    out = set()
    for item in drc["unconnected_items"]:
        for sub in item.get("items", []):
            d = sub.get("description", "")
            m = re.match(r"Pad (\S+) \[([^\]]+)\] of (\S+)", d)
            if m and m.group(2) in nets:
                out.add((m.group(3), m.group(1)))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("board", type=Path)
    ap.add_argument("--plane", action="append", required=True, metavar="NET=LAYER",
                    help="e.g. GND=In1.Cu (repeatable)")
    ap.add_argument("--pitch", type=float, default=0.8)
    ap.add_argument("--via", type=float, default=0.40)
    ap.add_argument("--drill", type=float, default=0.20)
    ap.add_argument("--clearance", type=float, default=0.15)
    ap.add_argument("--fanout", metavar="REF",
                    help="fan out EVERY plane-net pad of this footprint, rather than "
                         "only the ones DRC currently calls unconnected. Use this "
                         "BEFORE routing: fanout placed afterwards has to thread "
                         "between tracks that are already there.")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--cli", default=None)
    args = ap.parse_args()

    planes = dict(p.split("=", 1) for p in args.plane)
    cli = find_cli(args.cli)
    text = args.board.read_text()

    if args.fanout:
        want = {(ref, pad)
                for ref, _ox, _oy, _rot, ps in footprints(text) if ref == args.fanout
                for pad, _x, _y, net in ps if net in planes}
        if not want:
            raise SystemExit(f"{args.fanout}: no pads on {', '.join(planes)}")
        print(f"{args.board.name}: fanning out {args.fanout}")
        print(f"  pads on {', '.join(planes)}: {len(want)}")
    else:
        drc = run_drc(cli, args.board)
        want = unconnected_pads(drc, set(planes))
        print(f"{args.board.name}: {len(drc['unconnected_items'])} unconnected items")
        print(f"  pads on {', '.join(planes)} that DRC reports unconnected: {len(want)}")
    if not want:
        return 0

    vias, pads = existing(text)
    off = args.pitch / 2.0
    # Keep to the pad grid's diagonal gaps; a via anywhere else on a 0.8 mm pitch
    # cannot make clearance to the four balls around it.
    diagonals = [(off, off), (-off, off), (off, -off), (-off, -off)]
    min_via_gap = args.via + args.clearance
    min_pad_gap = args.via / 2 + 0.2 + args.clearance

    added, skipped = [], []
    for ref, _ox, _oy, _rot, ps in footprints(text):
        for pad, x, y, net in ps:
            if (ref, pad) not in want or net not in planes:
                continue
            for dx, dy in diagonals:
                vx, vy = x + dx, y + dy
                if any(math.hypot(vx - ax, vy - ay) < min_via_gap for ax, ay in vias):
                    continue
                if any(math.hypot(vx - ax, vy - ay) < min_pad_gap for ax, ay in pads):
                    continue
                added.append((ref, pad, net, x, y, vx, vy))
                vias.append((vx, vy))
                break
            else:
                skipped.append((ref, pad, net))

    print(f"  dogbones to add : {len(added)}")
    if skipped:
        print(f"  no free diagonal : {len(skipped)} "
              f"({', '.join(f'{r}.{p}' for r, p, _n in skipped[:6])}"
              f"{'...' if len(skipped) > 6 else ''})")
    if not args.apply:
        print("  (report only; pass --apply to write)")
        return 0
    if not added:
        return 0

    ns = uuid.UUID("29defa49-d385-58f2-b9e7-cb1252f93818")
    chunks = []
    for ref, pad, net, x, y, vx, vy in added:
        key = f"stitch:{ref}:{pad}"
        chunks.append(
            # A through via, not F.Cu->plane.  Stopping at the plane makes it a
            # blind via, which on a 4-layer board is a different and far more
            # expensive process (sequential lamination) for no benefit: a through
            # via reaches the same plane and the layers it passes get an antipad.
            f'\t(via\n\t\t(at {vx:g} {vy:g})\n\t\t(size {args.via:g})\n'
            f'\t\t(drill {args.drill:g})\n\t\t(layers "F.Cu" "B.Cu")\n'
            f'\t\t(net "{net}")\n\t\t(uuid "{uuid.uuid5(ns, key)}")\n\t)\n'
            f'\t(segment\n\t\t(start {x:g} {y:g})\n\t\t(end {vx:g} {vy:g})\n'
            f'\t\t(width {args.via / 2:g})\n\t\t(layer "F.Cu")\n'
            f'\t\t(net "{net}")\n\t\t(uuid "{uuid.uuid5(ns, key + ":seg")}")\n\t)\n')

    close = text.rstrip().rfind(")")
    text = text[:close] + "".join(chunks) + text[close:]
    args.board.write_text(text)

    after = run_drc(cli, args.board)
    errs = [v for v in after["violations"] if v["severity"] == "error"]
    print(f"  -> {len(after['unconnected_items'])} unconnected, "
          f"{len(after['violations'])} violations, {len(errs)} errors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
