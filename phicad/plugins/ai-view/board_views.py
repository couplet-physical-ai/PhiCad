"""Render the PCB, the schematic and a 3D view of the open project to PNG.

This backs the AI View window's view tabs.  Everything here is done by shelling out to
`kicad-cli`, deliberately:

  * the IPC API has no "give me a picture" call, and
  * the plugin runs in its own process, so it cannot draw with the editor's GAL canvas.

Non-obvious things this module encodes, each of which cost a debugging round:

  * `pcb export svg` takes a FILE for --mode-single but a DIRECTORY for --mode-multi
    (the default).  Passing a directory to single mode fails with the unhelpful
    "Failed to create file '<dir>'", and passing no --layers at all silently plots
    nothing useful.  This is the same trap that made verify.sh's export-svg step fail.
  * `pcb render` honours neither --theme nor the project's colour theme; only
    `export svg` does.  So the 2D tabs go through SVG and the 3D tab does not.
  * Tk cannot display SVG.  Rasterising needs rsvg-convert or cairosvg; both are
    checked, and a clear error is raised rather than showing an empty tab.
  * A schematic is optional.  A board generated by script (like the Teensy demo) has
    no .kicad_sch at all, so the schematic tab must say so instead of erroring.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass


# 2D layer sets.  Edge.Cuts is in every set so the board outline is always visible --
# without it a copper-only plot floats in space with no frame of reference.
LAYERS_FRONT = "F.Cu,F.Silkscreen,F.Mask,Edge.Cuts"
LAYERS_BACK = "B.Cu,B.Silkscreen,B.Mask,Edge.Cuts"
# Back copper FIRST, front last.  The layer order in --layers is the PAINT order, and a
# filled ground pour on B.Cu is a solid sheet: drawn last it buries every front trace under
# it, which is what "Both" looked like -- a blue rectangle with a few red fragments showing
# through the clearance gaps.  Painting F.Cu last puts the front on top where it belongs and
# leaves the back readable underneath.
LAYERS_BOTH = "B.Cu,F.Cu,F.Silkscreen,Edge.Cuts"

RENDER_TIMEOUT_S = 180.0


class RenderError(RuntimeError):
    """A view could not be produced.  The message is shown in the tab itself."""


class NoSchematic(RenderError):
    """The project has no .kicad_sch.  Distinct so the tab can explain rather than alarm."""


@dataclass
class Paths:
    """Where the open project lives, resolved from the board path the API reports."""

    board: str

    @property
    def project_dir(self) -> str:
        return os.path.dirname(os.path.abspath(self.board))

    @property
    def stem(self) -> str:
        return os.path.splitext(os.path.basename(self.board))[0]

    @property
    def schematic(self) -> str:
        return os.path.join(self.project_dir, self.stem + ".kicad_sch")

    def has_schematic(self) -> bool:
        return os.path.isfile(self.schematic)


def find_kicad_cli() -> str:
    """Locate kicad-cli.

    Order: explicit override, then the build tree this plugin was installed from (found
    via the recorded venv-path, which points into <repo>/build/venv), then PATH, then the
    installed .app.  The build tree comes before PATH on purpose: when running a fork you
    want the fork's binary, not whatever a package manager put in /usr/local/bin.
    """
    override = os.environ.get("PHICAD_KICAD_CLI", "").strip()
    if override:
        if os.access(override, os.X_OK):
            return override
        raise RenderError(f"PHICAD_KICAD_CLI is set but not executable: {override}")

    here = os.path.dirname(os.path.abspath(__file__))
    venv_file = os.path.join(here, "venv-path")
    if os.path.isfile(venv_file):
        try:
            with open(venv_file, encoding="utf-8") as fh:
                py = fh.read().strip()
            # <repo>/build/venv/bin/python -> <repo>
            repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(py))))
            for build in ("mac-dev", "mac-release", "mac-debug"):
                cand = os.path.join(repo, "build", build, "kicad",
                                    "PhiCad.app", "Contents", "MacOS", "kicad-cli")
                if os.access(cand, os.X_OK):
                    return cand
        except OSError:
            pass

    found = shutil.which("kicad-cli")
    if found:
        return found

    for app in ("/Applications/PhiCad.app", "/Applications/KiCad/KiCad.app"):
        cand = os.path.join(app, "Contents", "MacOS", "kicad-cli")
        if os.access(cand, os.X_OK):
            return cand

    raise RenderError("kicad-cli not found; set PHICAD_KICAD_CLI to its full path")


def _run(argv: list[str]) -> str:
    """Run kicad-cli with the build-tree env it needs.  Returns combined output."""
    env = dict(os.environ)
    # Required when the binary lives in a build tree rather than an installed bundle;
    # harmless otherwise.
    env["KICAD_RUN_FROM_BUILD_DIR"] = "1"
    # Never let a plugin render inherit the API socket: a child kicad-cli that connects
    # back to the editor can deadlock against the very handler that spawned us.
    env.pop("KICAD_API_SOCKET", None)
    env.pop("KICAD_API_TOKEN", None)
    try:
        proc = subprocess.run(argv, capture_output=True, text=True,
                              timeout=RENDER_TIMEOUT_S, env=env)
    except subprocess.TimeoutExpired as exc:
        raise RenderError(f"render timed out after {RENDER_TIMEOUT_S:.0f}s") from exc
    except OSError as exc:
        raise RenderError(f"could not run kicad-cli: {exc}") from exc

    out = (proc.stdout or "") + (proc.stderr or "")
    if proc.returncode != 0:
        # SIGABRT with no output is almost always the macOS directory-services wedge, not
        # anything to do with the board: kicad-cli resolves the user at startup, so even
        # `kicad-cli version` aborts.  Translate it, because "exited -6" tells the user
        # nothing and sends them looking for a board problem that does not exist.
        if proc.returncode in (-6, 134) and not out.strip():
            raise RenderError(
                "kicad-cli aborted immediately (SIGABRT) with no output.\n\n"
                "This is almost always macOS directory services (opendirectoryd) having "
                "stopped answering, not a problem with the board -- every kicad-cli run "
                "aborts the same way, including `kicad-cli version`.\n\n"
                "Check with:  dscl . -read /Users/$(whoami) RecordName\n"
                "If that reports eServerError, the only fix is a REBOOT (sudo and "
                "launchctl both need the daemon that is down).")
        tail = "\n".join(l for l in out.splitlines() if l.strip())[-600:]
        raise RenderError(f"kicad-cli exited {proc.returncode}:\n{tail}")
    return out


def _svg_to_png(svg: str, png: str, width: int) -> None:
    """Rasterise an SVG.  Tk has no SVG support, so this is not optional."""
    rsvg = shutil.which("rsvg-convert")
    if rsvg:
        _run([rsvg, "-w", str(width), "-o", png, svg])
        if os.path.isfile(png) and os.path.getsize(png) > 0:
            return

    try:
        import cairosvg  # noqa: PLC0415  (optional dependency, probed at call time)
    except ImportError as exc:
        raise RenderError(
            "cannot rasterise SVG: install librsvg (brew install librsvg) "
            "or cairosvg (pip install cairosvg)") from exc
    try:
        cairosvg.svg2png(url=svg, write_to=png, output_width=width)
    except Exception as exc:                      # cairosvg raises many types
        raise RenderError(f"cairosvg failed: {exc}") from exc


def render_pcb(paths: Paths, out_png: str, layers: str = LAYERS_BOTH,
               width: int = 1600, theme: str | None = None) -> str:
    """Plot the board to PNG via SVG.  Returns the PNG path."""
    if not os.path.isfile(paths.board):
        raise RenderError(f"board file not found: {paths.board}")

    with tempfile.TemporaryDirectory(prefix="aiview-pcb-") as tmp:
        svg = os.path.join(tmp, "pcb.svg")
        argv = [find_kicad_cli(), "pcb", "export", "svg",
                # --mode-single wants a FILE here.  Multi mode (the default) wants a
                # directory and writes one file per layer, which is not what a single
                # tab image needs.
                "-o", svg,
                "--layers", layers,
                "--mode-single",
                "--exclude-drawing-sheet",
                "--fit-page-to-board"]
        if theme:
            argv += ["--theme", theme]
        argv.append(paths.board)
        _run(argv)

        if not os.path.isfile(svg):
            raise RenderError("kicad-cli reported success but wrote no SVG")
        _svg_to_png(svg, out_png, width)

    return out_png


def render_3d(paths: Paths, out_png: str, side: str = "top",
              width: int = 1400, height: int = 1000,
              rotate: str | None = None) -> str:
    """Render the 3D view.  `side` is top|bottom|left|right|front|back."""
    if not os.path.isfile(paths.board):
        raise RenderError(f"board file not found: {paths.board}")

    argv = [find_kicad_cli(), "pcb", "render",
            "-o", out_png,
            "--side", side,
            "--width", str(width),
            "--height", str(height),
            "--quality", "high",
            # The board's own stackup colours look far closer to the editor's 3D view
            # than the default render preset does.
            "--use-board-stackup-colors"]
    if rotate:
        argv += ["--rotate", rotate]
    argv.append(paths.board)
    _run(argv)

    if not os.path.isfile(out_png):
        raise RenderError("kicad-cli reported success but wrote no 3D image")
    return out_png


def _trim(png: str, margin: int = 24) -> None:
    """Crop the empty page around a schematic, in place.

    A sheet is sized to its page, not to its contents: the demo's symbols occupy the top
    left third of an A4 and the rest is blank paper, so the tab scaled the whole page
    down to fit and the part values became unreadable.  There is no --fit-page-to-board
    for `sch export`, so the crop happens here.

    Guarded rather than required: Pillow missing means the tab still gets its picture,
    just with the margins on.  The corner pixel is the background rather than an assumed
    colour, so this works whatever theme drew the sheet.
    """
    try:
        from PIL import Image, ImageChops              # noqa: PLC0415
    except ImportError:
        return
    try:
        image = Image.open(png)
        image.load()
        # Measured in RGB even when the render has an alpha band.  Pillow's getbbox()
        # uses ONLY the alpha channel when there is one, and every pixel of a difference
        # against an opaque reference has alpha 0 -- so the RGBA path returned a
        # one-pixel-tall box and cropped the schematic to a 1800x25 strip.
        flat = image.convert("RGB")
        reference = Image.new("RGB", flat.size, flat.getpixel((0, 0)))
        box = ImageChops.difference(flat, reference).getbbox()
        if not box:
            return                                     # a blank sheet: nothing to crop
        left, top, right, bottom = box
        image.crop((max(0, left - margin), max(0, top - margin),
                    min(image.width, right + margin),
                    min(image.height, bottom + margin))).save(png)
    except Exception:                                   # noqa: BLE001
        return                                          # the untrimmed render is fine


def render_schematic(paths: Paths, out_png: str, width: int = 1800,
                     theme: str | None = None) -> str:
    """Plot the schematic to PNG.

    Raises NoSchematic when the project has none -- a script-generated board is a
    perfectly valid project with no .kicad_sch, and that deserves an explanation in the
    tab rather than a red error.
    """
    if not paths.has_schematic():
        raise NoSchematic(
            f"This project has no schematic ({os.path.basename(paths.schematic)} "
            f"does not exist).\n\n"
            f"The board was created directly (for example by a generator script), so "
            f"there is nothing to plot. The PCB and 3D tabs work normally.")

    with tempfile.TemporaryDirectory(prefix="aiview-sch-") as tmp:
        # `sch export svg` writes one file per sheet into a DIRECTORY.
        #
        # WITH its background, unlike the board plot.  --no-background-color leaves the
        # PNG transparent, and the tab composites that onto the near-black canvas the
        # board plots need -- so a schematic drawn in navy on cream (the theme's
        # schematic.background is rgb(252,252,245)) came out as dark ink on a dark
        # canvas.  A schematic is a sheet of paper; it keeps its paper.
        argv = [find_kicad_cli(), "sch", "export", "svg",
                "-o", tmp, "--exclude-drawing-sheet"]
        if theme:
            argv += ["--theme", theme]
        argv.append(paths.schematic)
        _run(argv)

        svgs = sorted(f for f in os.listdir(tmp) if f.lower().endswith(".svg"))
        if not svgs:
            raise RenderError("kicad-cli wrote no schematic SVG")
        # Root sheet only.  Multi-sheet designs would need a sheet picker; the tab
        # header says which sheet is shown so this is honest rather than silent.
        #
        # Rasterised at twice the asked-for width because _trim then throws most of it
        # away: the demo's symbols cover 45% of the page, so a 1800 px page became an
        # 804 px picture and the part values went soft.  Doubling first lands the crop
        # near the width that was actually requested.
        _svg_to_png(os.path.join(tmp, svgs[0]), out_png, min(4000, width * 2))
        _trim(out_png)
        return out_png
