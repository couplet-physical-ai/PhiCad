"""Project scaffolding: the empty, openable project a netlist gets imported into.

The gap this fills
------------------
`kicad-cli` has no "new project" command, and `resources/project_template/` is consumed only
by the GUI.  So an agent starting from a prompt has had nowhere to start: the Teensy demo
hand-embeds a `.kicad_pro` as a 90-line string literal (`generate_board.py:1554`) and writes
its board header inline.  Every new project copied that by hand.

`scaffold()` writes both files from the design's own rules, so the design rules an agent
declared in the IR are the rules DRC will actually enforce — rather than the two drifting
apart, which is how a board passes its author's intent and fails the fab's.

Format notes, verified against a board this fork wrote
------------------------------------------------------
* Board files are `version 20260831` and copper layer numbers are **even**:
  `F.Cu = 0`, `B.Cu = 2`, `In1.Cu = 4`, `In2.Cu = 6` … (`include/layer_ids.h:60-91`).
  Note B.Cu sits numerically *before* the inner layers; ordering the list by number would
  put the back copper in the middle of the stack.
* `.kicad_pro` is JSON with `meta.version 3`; net classes live under `net_settings` with
  their own `meta.version 4`.
* Writing the board is enough to open it: the outline comes later, because with
  `outline: auto` the board's size is a *result* of placement, not an input to it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

_HERE = Path(__file__).resolve().parent
if str(_HERE) not in sys.path:
    sys.path.insert(0, str(_HERE))

from ir import Design, MIN_HOLE_SPACING  # noqa: E402

BOARD_VERSION = "20260831"
GENERATOR = "phicad-synth"
GENERATOR_VERSION = "10.99"

# (number, name, type) for the non-copper layers every board carries, in the order this
# fork writes them.
_USER_LAYERS: Tuple[Tuple[int, str, str], ...] = (
    (9, "F.Adhes", "user"), (11, "B.Adhes", "user"),
    (13, "F.Paste", "user"), (15, "B.Paste", "user"),
    (5, "F.SilkS", "user"), (7, "B.SilkS", "user"),
    (1, "F.Mask", "user"), (3, "B.Mask", "user"),
    (17, "Dwgs.User", "user"), (19, "Cmts.User", "user"),
    (21, "Eco1.User", "user"), (23, "Eco2.User", "user"),
    (25, "Edge.Cuts", "user"), (27, "Margin", "user"),
    (31, "F.CrtYd", "user"), (29, "B.CrtYd", "user"),
    (35, "F.Fab", "user"), (33, "B.Fab", "user"),
)


def copper_layers(count: int) -> List[Tuple[int, str]]:
    """The copper stack for an N-layer board, front to back.

    F.Cu, then inner layers in order, then B.Cu — which is the physical order, not the
    numeric one (`B.Cu` is 2 while `In1.Cu` is 4).
    """
    if count < 1:
        raise ValueError(f"a board needs at least one copper layer, got {count}")
    stack: List[Tuple[int, str]] = [(0, "F.Cu")]
    for i in range(1, count - 1):
        stack.append((2 + 2 * i, f"In{i}.Cu"))
    if count > 1:
        stack.append((2, "B.Cu"))
    return stack


def board_text(design: Design) -> str:
    """An empty but openable board carrying the design's identity and layer stack."""
    lines: List[str] = [
        "(kicad_pcb",
        f"\t(version {BOARD_VERSION})",
        f'\t(generator "{GENERATOR}")',
        f'\t(generator_version "{GENERATOR_VERSION}")',
        "\t(general",
        f"\t\t(thickness {design.board.thickness})",
        "\t\t(legacy_teardrops no)",
        "\t)",
        '\t(paper "A4")',
        "\t(title_block",
        f'\t\t(title "{_escape(design.title or design.project)}")',
        f'\t\t(rev "{_escape(design.rev)}")',
        f'\t\t(company "{_escape(design.company)}")',
        '\t\t(comment 1 "generated by phicad-synth from the design IR")',
        "\t)",
        "\t(layers",
    ]
    for number, name in copper_layers(design.board.layers):
        lines.append(f'\t\t({number} "{name}" signal)')
    for number, name, kind in _USER_LAYERS:
        lines.append(f'\t\t({number} "{name}" {kind})')
    lines += [
        "\t)",
        "\t(setup",
        "\t\t(pad_to_mask_clearance 0.05)",
        "\t\t(allow_soldermask_bridges_in_footprints no)",
        "\t)",
        ")",
        "",
    ]
    return "\n".join(lines)


def _escape(text: str) -> str:
    return str(text).replace("\\", "\\\\").replace('"', '\\"')


def project_dict(design: Design) -> Dict:
    """The `.kicad_pro` contents, with DRC limits taken from the design's own rules.

    `min_*` values are the fab's floor, not the design's target: a 0.25 mm nominal track on
    a 0.15 mm minimum leaves the router room to neck down at a pad without DRC objecting.
    The design states both, so neither has to be guessed here.
    """
    rules = design.rules
    widths = sorted({0.0, rules.track_width, *rules.track_widths.values()})

    classes: List[Dict] = [{
        "bus_width": 0.25,
        "clearance": rules.clearance,
        "diff_pair_gap": 0.25,
        "diff_pair_width": 0.2,
        "line_style": 0,
        "microvia_diameter": 0.3,
        "microvia_drill": 0.1,
        "name": "Default",
        "pcb_color": "rgba(0, 0, 0, 0.000)",
        "priority": 2147483647,
        "schematic_color": "rgba(0, 0, 0, 0.000)",
        "track_width": rules.track_width,
        "via_diameter": rules.via_diameter,
        "via_drill": rules.via_drill,
        "wire_width": 6.0,
    }]

    patterns: List[Dict] = []
    # A net with its own declared width becomes its own class, so the width is enforced by
    # the netclass rather than only honoured by whoever draws the track.  A mixed-width net
    # is not a DRC error, so without this nothing would ever report the drift — exactly the
    # failure `generate_board.py:570` documents ("SDA and SCL trunks ended up 0.3 mm while
    # every tap into them was 0.25 mm ... nothing complained").
    for net in sorted(rules.track_widths):
        width = rules.track_widths[net]
        name = f"W{width:g}".replace(".", "p")
        if not any(c["name"] == name for c in classes):
            classes.append({
                "clearance": rules.clearance,
                "name": name,
                "priority": 1,
                "track_width": width,
                "via_diameter": rules.via_diameter,
                "via_drill": rules.via_drill,
            })
        patterns.append({"netclass": name, "pattern": net})

    return {
        "board": {
            "design_settings": {
                "defaults": {
                    "board_outline_line_width": 0.1,
                    "copper_line_width": rules.track_width,
                    "silk_line_width": 0.15,
                    "silk_text_size_h": 1.0,
                    "silk_text_size_v": 1.0,
                    "silk_text_thickness": 0.15,
                    "other_line_width": 0.15,
                },
                "diff_pair_dimensions": [],
                "drc_exclusions": [],
                "rules": {
                    "max_error": 0.005,
                    "min_clearance": rules.clearance - 0.05 if rules.clearance > 0.05
                    else rules.clearance,
                    "min_connection": rules.min_track_width,
                    "min_copper_edge_clearance": rules.edge_clearance,
                    "min_hole_clearance": MIN_HOLE_SPACING,
                    "min_hole_to_hole": MIN_HOLE_SPACING,
                    "min_microvia_diameter": 0.2,
                    "min_microvia_drill": 0.1,
                    "min_silk_clearance": 0.0,
                    "min_text_height": 0.8,
                    "min_text_thickness": 0.08,
                    "min_through_hole_diameter": rules.min_hole,
                    "min_track_width": rules.min_track_width,
                    "min_via_annular_width": 0.13,
                    "min_via_diameter": 0.45,
                    "solder_mask_to_copper_clearance": 0.0,
                    "use_height_for_length_calcs": True,
                },
                "rule_severities": {
                    "copper_sliver": "warning",
                    "footprint_type_mismatch": "ignore",
                    "lib_footprint_issues": "warning",
                    "lib_footprint_mismatch": "ignore",
                },
                "track_widths": widths,
                "via_dimensions": [
                    {"diameter": 0.0, "drill": 0.0},
                    {"diameter": rules.via_diameter, "drill": rules.via_drill},
                ],
                "zones_allow_external_fillets": False,
            }
        },
        "meta": {"filename": f"{design.project}.kicad_pro", "version": 3},
        "net_settings": {
            "classes": classes,
            "meta": {"version": 4},
            # "netclass_patterns", NOT "net_class_patterns".  KiCad's reader keys on the
            # former (common/project/net_settings.cpp:363), and an unrecognised key is
            # dropped in silence -- so with the extra underscore every per-net width and
            # clearance the design declared was written into the file, ignored by DRC, and
            # nothing anywhere said so.
            "netclass_patterns": patterns,
        },
    }


def scaffold(design: Design, out_dir, overwrite: bool = False) -> Dict[str, Path]:
    """Write `<project>.kicad_pro` and an empty `<project>.kicad_pcb` into `out_dir`.

    Returns the paths written.  Refuses to overwrite an existing board unless asked: a
    scaffold that silently replaced a routed board would destroy work that no amount of
    regeneration brings back.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    pro = out / f"{design.project}.kicad_pro"
    pcb = out / f"{design.project}.kicad_pcb"

    for path in (pro, pcb):
        if path.exists() and not overwrite:
            raise FileExistsError(
                f"{path} already exists. Pass overwrite=True (CLI: --force) if replacing "
                "it is really what you want — an existing board may hold placement and "
                "routing that the design IR does not describe.")

    pro.write_text(json.dumps(project_dict(design), indent=2) + "\n", encoding="utf-8")
    pcb.write_text(board_text(design), encoding="utf-8")
    return {"project": pro, "board": pcb}


if __name__ == "__main__":
    # Smoke test:  python3 phicad/synth/project.py design.json out/
    from ir import load                                            # noqa: PLC0415

    if len(sys.argv) < 3:
        print("usage: project.py <design.json> <out-dir>", file=sys.stderr)
        raise SystemExit(2)
    d = load(sys.argv[1])
    written = scaffold(d, sys.argv[2], overwrite="--force" in sys.argv)
    for kind, path in written.items():
        print(f"{kind}: {path}")
